    private void salvarDadosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarDadosActionPerformed
       String idStr = tId.getText();
        String nome = tNome.getText();
        String cpf = tCpf.getText();
        String telefone = tTelefone.getText();
        String sexo = tSexo.getText();
        String email = tEmail.getText();
        String senha = new String(tSenha.getPassword());

        String idadeStr = tIdade.getText();
        String pesoStr = tPeso.getText();
        String alturaStr = tAltura.getText(); 

        String objetivo = tObjetivo.getText();
        String restricaoFisica = tRestricaoFisica.getText();

        
        if (idStr.isEmpty() || nome.isEmpty() || cpf.isEmpty() || telefone.isEmpty() || sexo.isEmpty() ||
            email.isEmpty() || senha.isEmpty() || idadeStr.isEmpty() || pesoStr.isEmpty() ||
            alturaStr.isEmpty() || objetivo.isEmpty() || restricaoFisica.isEmpty()) {

            statusLabel.setText("Todos os campos devem ser preenchidos!"); 
            JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos.", "Erro de Validação", JOptionPane.WARNING_MESSAGE);
            return;
        }
 
        int idCliente;
        int idade;
        double peso;
        double altura;

        try {
            idCliente = Integer.parseInt(idStr);
            idade = Integer.parseInt(idadeStr);
            peso = Double.parseDouble(pesoStr);
            altura = Double.parseDouble(alturaStr);
        } catch (NumberFormatException ex) {
            statusLabel.setText("ID, Idade, Peso e Altura devem ser números válidos!");
            JOptionPane.showMessageDialog(this, "Por favor, insira valores numéricos válidos para ID, Idade, Peso e Altura.", "Erro de Formato", JOptionPane.ERROR_MESSAGE);
            return; 
        }


        for (Cliente c : listaClientes) { 
            if (c.getId() == idCliente) {
                statusLabel.setText("Erro: ID já existente. Por favor, insira um ID único.");
                JOptionPane.showMessageDialog(this, "O ID " + idCliente + " já está em uso. Por favor, insira um ID diferente.", "Erro de ID", JOptionPane.WARNING_MESSAGE);
                return; 
            }
        }

        
        Cliente novoCliente;
        novoCliente = new Cliente(
                idCliente,nome,cpf,telefone,email,senha,sexo,idade,peso,altura,objetivo,restricaoFisica
        );

        listaClientes.add(novoCliente);

        statusLabel.setText("Cliente '" + nome + "' salvo com sucesso!");
        JOptionPane.showMessageDialog(this, "Cliente '" + nome + "' salvo com sucesso!\nTotal de clientes: " + listaClientes.size(), "Sucesso", JOptionPane.INFORMATION_MESSAGE);

        tId.setText("");
        tNome.setText("");
        tCpf.setText("");
        tTelefone.setText("");
        tSexo.setText("");
        tEmail.setText("");
        tSenha.setText("");
        tIdade.setText("");
        tPeso.setText("");
        tAltura.setText(""); 
        tObjetivo.setText("");
        tRestricaoFisica.setText("");

        statusLabel.setText("");

        MenuCliente menuCliente = new MenuCliente();
        menuCliente.setVisible(true);            
        this.dispose();
    }

